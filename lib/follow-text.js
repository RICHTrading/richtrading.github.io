function sheetKind(ev) {
  if (ev.kind === 'entry') return ev.manual === true ? '직접 진입' : `${Number.isInteger(ev.stage) ? `${ev.stage}차 ` : ''}진입`;
  if (ev.kind === 'dca') return ev.manual === true ? '직접 추가 진입' : Number.isInteger(ev.stage) ? `${ev.stage}차 진입` : '추가 진입'; // E1 흐름 낱말
  if (ev.kind === 'adjust') return '익절·손절가 조정';
  return '종료';
}

